import 'dart:typed_data';

import 'package:flutter/material.dart';
import 'package:flutter/services.dart' show rootBundle;
import 'package:get/get.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';

class BmiResultController extends GetxController {
  late String name;
  late String gender;
  late int age;
  late String height;
  late int weight;
  late double bmi;
  late String category;
  late Color categoryColor;
  late double targetWeight;
  late double weightLoss;
  late double sliderPosition;

  // True while the PDF report is being built/shared
  final RxBool isGeneratingReport = false.obs;

  // Path to the logo used in the PDF report header.
  // Make sure this is declared under flutter/assets in pubspec.yaml.
  static const String _logoAssetPath = 'assets/phir_health_app_icon.png';

  @override
  void onInit() {
    super.onInit();
    name = Get.arguments?['name'] ?? 'User';
    gender = Get.arguments?['gender'] ?? 'Male';
    age = Get.arguments?['age'] ?? 28;
    height = Get.arguments?['height'] ?? "5'9";
    weight = Get.arguments?['weight'] ?? 110;
    _calculate();
  }

  void _calculate() {
    final double heightM = _heightToMeters(height);

    // BMI formula
    bmi = weight / (heightM * heightM);
    bmi = double.parse(bmi.toStringAsFixed(1));

    // Category + color + slider
    if (bmi < 18.5) {
      category = 'bmi_result_underweight'.tr;
      categoryColor = const Color(0xFF60A5FA);
    } else if (bmi < 25) {
      category = 'bmi_result_normal'.tr;
      categoryColor = const Color(0xFF4ADE80);
    } else if (bmi < 30) {
      category = 'bmi_result_overweight'.tr;
      categoryColor = const Color(0xFFFBBF24);
    } else {
      category = 'bmi_result_obese'.tr;
      categoryColor = const Color(0xFFEF4444);
    }

    // Exact slider position from BMI
    // BAAD MEIN — category zones ke hisaab se:
    if (bmi < 18.5) {
      // Underweight zone — 0.0 to 0.25
      sliderPosition = ((bmi / 18.5) * 0.25).clamp(0.0, 0.24);
    } else if (bmi < 25) {
      // Normal zone — 0.25 to 0.50
      sliderPosition = (0.25 + ((bmi - 18.5) / 6.5) * 0.25).clamp(0.25, 0.49);
    } else if (bmi < 30) {
      // Overweight zone — 0.50 to 0.75
      sliderPosition = (0.50 + ((bmi - 25) / 5) * 0.25).clamp(0.50, 0.74);
    } else {
      // Obese zone — 0.75 to 1.0
      sliderPosition = (0.75 + ((bmi - 30) / 10) * 0.25).clamp(0.75, 1.0);
    }

    // Target weight — Normal BMI upper limit (24.9)
    targetWeight = double.parse(
      (24.9 * heightM * heightM).toStringAsFixed(1),
    );

    // Weight loss — negative nahi aayega
    final double loss = weight - targetWeight;
    weightLoss = double.parse(
      loss.clamp(0.0, double.infinity).toStringAsFixed(1),
    );
  }

  // Height parse — 5'9 / 5'9" / 5 9 sab handle karta hai
  double _heightToMeters(String h) {
    try {
      h = h.replaceAll('"', '').replaceAll("'", ' ');
      final parts = h.trim().split(RegExp(r'\s+'));
      final int feet = int.tryParse(parts[0]) ?? 5;
      final int inches = parts.length > 1 ? (int.tryParse(parts[1]) ?? 0) : 0;
      return (feet * 12 + inches) * 0.0254;
    } catch (_) {
      return 1.75;
    }
  }

  void viewPlan() {
    // Aage connect karna ho toh yahan
  }

  // ===== DOWNLOAD / SHARE BMI REPORT (PDF, includes user name) =====
  Future<void> downloadReport() async {
    if (isGeneratingReport.value) return;
    isGeneratingReport.value = true;

    try {
      // Load the PHIR Health logo so it can be drawn into the PDF.
      final ByteData logoBytes = await rootBundle.load(_logoAssetPath);
      final pw.MemoryImage logoImage =
          pw.MemoryImage(logoBytes.buffer.asUint8List());

      final doc = pw.Document();

      doc.addPage(
        pw.MultiPage(
          pageFormat: PdfPageFormat.a4,
          margin: const pw.EdgeInsets.all(32),
          // Pinned to the bottom of every page, regardless of how much
          // content is above it. (footer/header only exist on MultiPage,
          // not on the single-page pw.Page widget.)
          footer: (context) {
            return pw.Container(
              alignment: pw.Alignment.center,
              margin: const pw.EdgeInsets.only(top: 12),
              child: pw.Text(
                'This report is generated by PHIR Health',
                style: pw.TextStyle(
                  fontSize: 9,
                  fontStyle: pw.FontStyle.italic,
                  color: PdfColors.grey600,
                ),
              ),
            );
          },
          build: (context) => [
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                      'BMI Report',
                      style: pw.TextStyle(
                        fontSize: 24,
                        fontWeight: pw.FontWeight.bold,
                      ),
                    ),
                    pw.SizedBox(height: 4),
                    pw.Text(
                      'Generated on ${_formattedDate(DateTime.now())}',
                      style: const pw.TextStyle(
                        fontSize: 10,
                        color: PdfColors.grey700,
                      ),
                    ),
                  ],
                ),
                pw.Image(logoImage, width: 80),
              ],
            ),
            pw.SizedBox(height: 20),
            pw.Divider(),
            pw.SizedBox(height: 12),
            _pdfRow('Name', name),
            _pdfRow('Gender', gender),
            _pdfRow('Age', '$age yrs'),
            _pdfRow('Height', height),
            _pdfRow('Weight', '$weight kg'),
            pw.SizedBox(height: 12),
            pw.Divider(),
            pw.SizedBox(height: 12),
            pw.Text(
              'BMI Result',
              style: pw.TextStyle(
                fontSize: 16,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
            pw.SizedBox(height: 10),
            _pdfRow('BMI Score', '$bmi'),
            _pdfRow('Category', category),
            _pdfRow('Target Weight', '$targetWeight kg'),
            _pdfRow('Weight to Lose', '$weightLoss kg'),
            pw.SizedBox(height: 24),
            pw.Text(
              'This report is generated for informational purposes only '
              'and is not a substitute for professional medical advice.',
              style: const pw.TextStyle(
                fontSize: 9,
                color: PdfColors.grey600,
              ),
            ),
          ],
        ),
      );

      final Uint8List bytes = await doc.save();
      final String safeName = name.trim().isEmpty
          ? 'User'
          : name.trim().replaceAll(RegExp(r'\s+'), '_');

      // Opens the native share/save sheet so the user can download or
      // send the PDF — works on Android, iOS and Web.
      await Printing.sharePdf(
        bytes: bytes,
        filename: 'BMI_Report_$safeName.pdf',
      );
    } catch (e) {
      Get.snackbar(
        'bmi_result_report_error_title'.tr,
        'bmi_result_report_error_body'.tr,
        snackPosition: SnackPosition.BOTTOM,
      );
    } finally {
      isGeneratingReport.value = false;
    }
  }

  pw.Widget _pdfRow(String label, String value) {
    return pw.Padding(
      padding: const pw.EdgeInsets.symmetric(vertical: 4),
      child: pw.Row(
        children: [
          pw.SizedBox(
            width: 130,
            child: pw.Text(
              label,
              style: const pw.TextStyle(
                fontSize: 12,
                color: PdfColors.grey700,
              ),
            ),
          ),
          pw.Text(
            value,
            style: pw.TextStyle(
              fontSize: 12,
              fontWeight: pw.FontWeight.bold,
            ),
          ),
        ],
      ),
    );
  }

  String _formattedDate(DateTime d) {
    const months = [
      'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
      'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec',
    ];
    return '${d.day} ${months[d.month - 1]} ${d.year}';
  }
}